-- LinkPulse database setup
-- Run this entire file in Supabase SQL Editor.
--
-- The frontend uses the anonymous Supabase client and a browser-local
-- visitor_id. This is suitable for a demo/no-account workspace, not for
-- authenticated multi-user ownership. Do not use the permissive policies
-- below for private production data without adding Supabase Auth or an API.

create table if not exists public.links (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  original_url text not null,
  short_code text not null unique,
  campaign text,
  click_limit integer,
  clicks_count integer not null default 0,
  expires_at timestamptz,
  is_disabled boolean not null default false
);

create table if not exists public.clicks (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  link_id bigint not null references public.links(id) on delete cascade,
  ip_address text,
  user_agent text,
  device_type text,
  country text
);

alter table public.links
  add column if not exists visitor_id text,
  add column if not exists password_hash text;

alter table public.clicks
  add column if not exists ip_address text,
  add column if not exists user_agent text,
  add column if not exists device_type text,
  add column if not exists country text;

create index if not exists links_visitor_id_idx
  on public.links (visitor_id);

create index if not exists links_short_code_idx
  on public.links (short_code);

create index if not exists clicks_link_id_created_at_idx
  on public.clicks (link_id, created_at desc);

-- The client hashes new passwords with SHA-256 before inserting them.
-- Existing plaintext values in password_hash must be recreated or migrated
-- before password protection is considered safe.

alter table public.links enable row level security;
alter table public.clicks enable row level security;

drop policy if exists "linkpulse public redirect lookup" on public.links;
create policy "linkpulse public redirect lookup"
  on public.links for select
  to anon, authenticated
  using (true);

drop policy if exists "linkpulse create browser link" on public.links;
create policy "linkpulse create browser link"
  on public.links for insert
  to anon, authenticated
  with check (visitor_id is not null);

drop policy if exists "linkpulse manage browser link" on public.links;
create policy "linkpulse manage browser link"
  on public.links for update
  to anon, authenticated
  using (true)
  with check (visitor_id is not null);

drop policy if exists "linkpulse delete browser link" on public.links;
create policy "linkpulse delete browser link"
  on public.links for delete
  to anon, authenticated
  using (true);

drop policy if exists "linkpulse record click" on public.clicks;
create policy "linkpulse record click"
  on public.clicks for insert
  to anon, authenticated
  with check (link_id is not null);

drop policy if exists "linkpulse read click analytics" on public.clicks;
create policy "linkpulse read click analytics"
  on public.clicks for select
  to anon, authenticated
  using (true);
